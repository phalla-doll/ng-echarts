import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = resolve(import.meta.dirname, '..');
const component = await readFile(
  resolve(root, 'projects/playground/src/app/linked/composed-dashboard.ts'),
  'utf8',
);
const app = await readFile(
  resolve(root, 'projects/playground/src/app/linked/dashboard-app.ts'),
  'utf8',
);
const wrapper = app.replace(/^import .*\n/gm, '');
const source = `${component}\n${wrapper}`;
const output = resolve(root, 'projects/playground/src/app/linked/composed-dashboard-source.ts');
const generated = await format(
  `// Generated by tools/generate-dashboard-example.mjs.\nexport const composedDashboardSource = ${JSON.stringify(source)};\n`,
  {
    ...(await resolveConfig(resolve(root, '.prettierrc'))),
    parser: 'typescript',
  },
);
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== generated)
    throw new Error('Run npm run dashboard:source after editing the dashboard or consumer App.');
} else {
  await writeFile(output, generated);
}
